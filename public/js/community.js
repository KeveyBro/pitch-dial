// Community results: the logic shared by the game (main.js), the results API (worker/index.js)
// and the tests. Pure functions only. The server never trusts the browser's scoring: it checks
// each shared game with normalizeGame and recomputes every miss itself.
import { centsBetween } from './maths.js';
import { FAMILIES, familyInstruments } from './audio.js';

export const RANGES = { low: [80, 320], mid: [150, 900], wide: [60, 2000] };   // dial mode
export const VRANGES = { low: [98, 294], high: [196, 587] };                  // singing mode
export const MIN_ROUNDS = 5;     // scored rounds a game needs before it's shared (as for personal bests)
export const MIN_GAMES = 30;     // shared games a mode needs before players are shown a comparison

// Research benchmarks from HANDOFF.md, shown before (and alongside) the players' own results.
// Matching errors and discrimination thresholds aren't the same thing; the labels say which.
export const RESEARCH = {
  dial: [
    { cents: 6.2, label: 'Best 5% can hear', text: 'the best 5% of listeners can hear a 6.2-cent difference (Sci Rep, 2017)' },
    { cents: 13, label: 'Non-musicians, slider', text: 'non-musicians matching with a slider missed by 13 cents on average, and could replay the target (Hutchins et al., 2014)' }
  ],
  sing: [
    { cents: 38, label: 'Non-musicians, singing', text: 'non-musicians singing a note they had just heard missed by 38 cents on average (Hutchins et al., 2014)' }
  ]
};

/* ---------- research seed ---------- */
// So the comparison works from day one, each mode starts with SEED_GAMES modelled games: game
// averages spread evenly along a published distribution (quantiles, not random draws). They're
// kept apart from real games (histogram rows 'dial:research' and 'sing:research', from
// migrations/0002_research_seed.sql, generated by tools/make-seed.js), always labelled as
// research-based, and dropped from the comparison once a mode has SEED_UNTIL real games.
//   dial: pitch-discrimination thresholds of 918 adults (Sci Rep 2017, doi 10.1038/s41598-017-16526-8):
//         5% at 6.2¢, half at 14.5¢, 95% at 77.4¢. Discrimination isn't matching, but it's the same
//         order as non-musicians' 13¢ average when matching with a slider (Hutchins et al. 2014).
//   sing: single-pitch matching by 50 occasional singers (Berkowska & Dalla Bella 2013, Front.
//         Psychol.): median 87.8¢, mean 140.2¢, range 2.3–522.1¢. A log-normal with that median and
//         mean has σ = 0.9675, giving the 5th and 95th percentiles below; values are clipped to the range.
export const SEED_GAMES = 50;
export const SEED_UNTIL = 100;
export const SEED = {
  dial: { p5: 6.2, p50: 14.5, p95: 77.4, min: 0, max: Infinity, about: 'pitch discrimination in 918 adults' },
  sing: { p5: 17.9, p50: 87.8, p95: 431.1, min: 2.3, max: 522.1, about: 'single-note singing by 50 untrained adults' }
};
// inverse of the standard normal CDF (Acklam's rational approximation, error < 1.2e-9)
function zOf(p) {
  const a = [-39.69683028665376, 220.9460984245205, -275.9285104469687, 138.357751867269, -30.66479806614716, 2.506628277459239];
  const b = [-54.47609879822406, 161.5858368580409, -155.6989798598866, 66.80131188771972, -13.28068155288572];
  const c = [-0.007784894002430293, -0.3223964580411365, -2.400758277161838, -2.549732539343734, 4.374664141464968, 2.938163982698783];
  const d = [0.007784695709041462, 0.3224671290700398, 2.445134137142996, 3.754408661907416];
  const q = Math.min(p, 1 - p);
  let z;
  if (q < 0.02425) {
    const r = Math.sqrt(-2 * Math.log(q));
    z = (((((c[0] * r + c[1]) * r + c[2]) * r + c[3]) * r + c[4]) * r + c[5]) / ((((d[0] * r + d[1]) * r + d[2]) * r + d[3]) * r + 1);
  } else {
    const r = (q - 0.5) * (q - 0.5);
    z = (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * (q - 0.5) / (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
  }
  return p < 0.5 ? z : -z;
}
// The seed's game averages for a mode: a log-normal through the 5th, 50th and 95th percentiles,
// with its own spread either side of the median (the high tail is longer for both studies).
export function seedAverages(mode) {
  const s = SEED[mode], k = zOf(0.95);
  const lo = Math.log(s.p50 / s.p5) / k, hi = Math.log(s.p95 / s.p50) / k;
  return Array.from({ length: SEED_GAMES }, (_, i) => {
    const z = zOf((i + 0.5) / SEED_GAMES);
    return Math.min(s.max, Math.max(s.min, s.p50 * Math.exp(z * (z < 0 ? lo : hi))));
  });
}
export function seedBins(mode) {
  const bins = new Array(BIN_COUNT).fill(0);
  for (const c of seedAverages(mode)) bins[binOf(c)]++;
  return bins;
}
// What the summary compares against: research and player games pooled until the mode has
// SEED_UNTIL real games, then players only. stats is GET /api/stats's body.
export function comparisonFor(stats, mode) {
  const players = stats.modes[mode] || { n: 0, bins: new Array(BIN_COUNT).fill(0) };
  const research = stats.modes[mode + ':research'];
  if (!research || players.n >= SEED_UNTIL) return { n: players.n, players: players.n, research: 0, bins: players.bins };
  return { n: players.n + research.n, players: players.n, research: research.n, bins: players.bins.map((v, i) => v + (research.bins[i] || 0)) };
}

/* ---------- validating a shared game ---------- */
const LISTEN = ['noob', 'easy', 'hard'], TIMES = [0, 30, 60];
const num = (x) => typeof x === 'number' && Number.isFinite(x);
const fail = (error) => ({ ok: false, error });

// Payload from the browser:
//   { v: 1, mode: 'dial'|'sing', input: 'live'|'upload'|null, family, listen, time, range, fold,
//     rounds: [[target Hz, answer Hz or null for a miss, instrument], ...] }
// Returns { ok: true, game } with the misses recomputed here, or { ok: false, error }.
export function normalizeGame(p) {
  if (!p || typeof p !== 'object' || p.v !== 1) return fail('unknown format');
  const sing = p.mode === 'sing';
  if (p.mode !== 'dial' && !sing) return fail('bad mode');
  if (sing ? !['live', 'upload'].includes(p.input) : p.input !== null) return fail('bad input');
  if (p.family !== 'random' && !Object.prototype.hasOwnProperty.call(FAMILIES, p.family)) return fail('bad family');
  if (!LISTEN.includes(p.listen) || !TIMES.includes(p.time)) return fail('bad timing');
  const ranges = sing ? VRANGES : RANGES;
  if (!Object.prototype.hasOwnProperty.call(ranges, p.range)) return fail('bad range');
  if (typeof p.fold !== 'boolean' || (p.fold && !sing)) return fail('bad octave setting');
  if (!Array.isArray(p.rounds) || p.rounds.length < 1 || p.rounds.length > 20) return fail('bad rounds');

  const [lo, hi] = ranges[p.range];
  const allowed = familyInstruments(p.family);
  const rounds = [];
  for (const r of p.rounds) {
    if (!Array.isArray(r) || r.length !== 3) return fail('bad round');
    const [target, you, inst] = r;
    if (!num(target) || target < lo * 0.995 || target > hi * 1.005) return fail('target out of range');
    if (!allowed.includes(inst)) return fail('bad instrument');
    if (you === null) { rounds.push([target, null, inst, null]); continue; }
    // the dial can't leave the range; a voice can, but not beyond what anyone can sing or hum
    if (!num(you) || (sing ? you < 40 || you > 2000 : you < lo * 0.995 || you > hi * 1.005)) return fail('answer out of range');
    // the same scoring as the game: in octave-fold mode, against the target in the octave sung
    const ref = p.fold ? target * Math.pow(2, Math.round(centsBetween(you, target) / 1200)) : target;
    rounds.push([target, you, inst, centsBetween(you, ref)]);
  }
  const scored = rounds.filter((r) => r[3] !== null);
  if (scored.length < MIN_ROUNDS) return fail(`fewer than ${MIN_ROUNDS} scored rounds`);
  // averaged before rounding, exactly as the game's summary does
  const avgCents = scored.reduce((s, r) => s + Math.abs(r[3]), 0) / scored.length;
  const meanCents = scored.reduce((s, r) => s + r[3], 0) / scored.length;
  for (const r of scored) r[3] = Math.round(r[3] * 100) / 100;
  return {
    ok: true,
    game: {
      mode: p.mode, input: p.input, family: p.family, listen: p.listen, time: p.time, range: p.range, fold: p.fold,
      scored: scored.length, missed: rounds.length - scored.length,
      avgCents: Math.round(avgCents * 100) / 100, meanCents: Math.round(meanCents * 100) / 100, rounds
    }
  };
}

/* ---------- histogram of game averages ---------- */
// The server keeps a running count of each mode's game averages in these bins, so reading the
// stats costs one row per mode however many games there are. Fine bins where most games land:
// 0.5¢ up to 50¢, 2¢ up to 200¢, 25¢ up to 1200¢, then one bin for anything beyond.
export const BIN_COUNT = 216;
export function binOf(c) {
  if (c < 50) return Math.max(0, Math.floor(c / 0.5));
  if (c < 200) return 100 + Math.floor((c - 50) / 2);
  if (c < 1200) return 175 + Math.floor((c - 200) / 25);
  return BIN_COUNT - 1;
}
export function binEdges(i) {
  if (i < 100) return [i * 0.5, (i + 1) * 0.5];
  if (i < 175) return [50 + (i - 100) * 2, 50 + (i - 99) * 2];
  if (i < 215) return [200 + (i - 175) * 25, 200 + (i - 174) * 25];
  return [1200, 2400];
}
// Share of games whose average miss is below c, spreading each bin's games evenly across it
export function fractionBelow(c, bins) {
  const total = bins.reduce((s, n) => s + n, 0);
  if (!total) return 0;
  let below = 0;
  for (let i = 0; i < bins.length; i++) {
    const [a, b] = binEdges(i);
    if (c >= b) below += bins[i];
    else { if (c > a) below += bins[i] * (c - a) / (b - a); break; }
  }
  return below / total;
}
// The average miss below which a share q (0–1) of games fall
export function quantile(q, bins) {
  const total = bins.reduce((s, n) => s + n, 0);
  if (!total) return null;
  let acc = 0;
  for (let i = 0; i < bins.length; i++) {
    if (!bins[i]) continue;
    if (acc + bins[i] >= q * total) {
      const [a, b] = binEdges(i);
      return a + (b - a) * (q * total - acc) / bins[i];
    }
    acc += bins[i];
  }
  return binEdges(bins.length - 1)[1];
}
